import { z } from "zod";
import type { ActionAdapter } from "../../dispatch/dispatcher.js";
import { DispatchFailure } from "../../dispatch/failure.js";
import type { ActionEnvelope, ActionResult } from "../../domain/actions.js";
import { MetaSender } from "../../channels/meta-send.js";

const targetSchema = z.object({
  channel: z.literal("whatsapp"),
  accountId: z.string().regex(/^\d{5,32}$/),
  recipientId: z.string().regex(/^\d{7,15}$/)
}).passthrough();

const bodySchema = z.object({
  templateName: z.string().min(1).max(512).regex(/^[a-z0-9_]+$/),
  languageCode: z.string().min(2).max(20).regex(/^[A-Za-z]{2,3}(?:[_-][A-Za-z]{2,4})?$/),
  bodyParameters: z.array(z.string().min(1).max(1024)).max(10).default([])
}).strict();

/** Explicit template action only; never generated by ordinary AI text replies. */
export class WhatsAppTemplateAdapter implements ActionAdapter {
  readonly provider = "meta";
  readonly capability = "messaging";
  readonly operation = "message.template.send";

  constructor(private readonly sender: MetaSender) {}

  async execute(action: ActionEnvelope): Promise<ActionResult> {
    const target = targetSchema.safeParse(action.target);
    const body = bodySchema.safeParse(action.body);
    if (!target.success || !body.success) {
      throw new DispatchFailure("Invalid WhatsApp template action", { retryable: false });
    }
    const result = await this.sender.sendWhatsAppTemplate({
      accountId: target.data.accountId,
      recipientId: target.data.recipientId,
      templateName: body.data.templateName,
      languageCode: body.data.languageCode,
      bodyParameters: body.data.bodyParameters
    });
    return result.providerMessageId === undefined ? {} : { providerResourceId: result.providerMessageId };
  }
}
