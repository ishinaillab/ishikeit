get("mfa-modal-proof-form").addEventListener("submit",async event=>{
  event.preventDefault();
  if(metaBusy || !metaOperation || !csrfToken)return;
  const code=get("mfa-modal-proof-code").value;
  if(!/^[0-9]{6}$/u.test(code))return;
  const proofFactorId=get("mfa-modal-proof-device").value;
  const operation=metaOperation;
  metaBusy=true;get("mfa-modal-proof-submit").disabled=true;
  try{
    if(operation.kind==="pre_enroll"){
      const proof=await request("/app/auth/mfa/totp/verify",
        {factorId:proofFactorId,code},csrfToken);
      if(!proof.ok)throw Error("Current authenticator code wasn't accepted.");
      const result=await proof.json();
      if(result.status!=="authenticated" || typeof result.csrfToken!=="string")
        throw Error("Authentication not confirmed.");
      csrfToken=result.csrfToken;setSessionExpiry(result);
      metaOperation=null;
      if(mfaState)mfaState.canEnroll=true;
      metaStageSet("connect");
      // The proof request is finished. Release its busy guard BEFORE
      // beginning a second, separately rate-limited enrollment request.
      metaBusy=false;
      await metaEnroll();
      return;
    }
    const payload={...operation,proofFactorId,code};
    const response=await request("/app/auth/mfa/preferences",payload,csrfToken);
    if(response.status===409){
      const state=await response.json();
      if(state.status==="authenticator_state_requires_signin"){
        metaClearKey();metaOperation=null;
        if(typeof metaDialog.close==="function" && metaDialog.open)metaDialog.close();
        metaDialog.hidden=true;
        showLogin("An authenticator change was only partially completed. Sign in again to review your actual connected devices.");
        return;
      }
    }
    if(response.status===429)throw Error("Security changes are rate-limited. Try again after the cooldown.");
    if(!response.ok)throw Error("Security change was not confirmed. Reopen this panel to check the actual factor state.");
    const result=await response.json();
    if(result.status==="authenticator_removed_signin_required"){
      metaClearKey();
      metaOperation=null;
      if(typeof metaDialog.close==="function" && metaDialog.open)metaDialog.close();
      metaDialog.hidden=true;
      showLogin("Authenticator removed. Sign in again to continue securely.");
      return;
    }
    if(result.status!=="changed" || typeof result.csrfToken!=="string")
      throw Error("Unexpected security response; reload to verify your settings.");
    csrfToken=result.csrfToken;
    metaOperation=null;get("mfa-modal-proof-code").value="";
    await metaRead();
    if(operation.kind==="rename"){
      const renamed=mfaState?.devices.find(x=>x.factorId===operation.factorId);
      if(renamed)metaSelected=renamed;
      metaStageSet("manage");
    }else if(operation.kind==="remove"){
      metaSelected=null;metaStageSet("manage");
    }else metaStageSet("overview");
  }catch(error){
    metaStatus(error instanceof Error?error.message:"Security change unsuccessful.");
  }finally{metaBusy=false;get("mfa-modal-proof-submit").disabled=false;}
});
