function metaBeginProof(operation,previous){
  if(!mfaState)return;
  const devices=mfaState.devices.filter(x=>x.enabled
    && !(operation.kind==="remove" && mfaState.devices.filter(y=>y.enabled).length>1
      && x.factorId===operation.factorId));
  if(!devices.length){metaStatus("No authenticator is available to verify this change.");return;}
  metaOperation=operation;
  metaProofReturn=previous;
  const select=get("mfa-modal-proof-device");select.replaceChildren();
  for(const device of devices){
    const option=document.createElement("option");
    option.value=device.factorId;option.textContent=device.label;select.append(option);
  }
  get("mfa-modal-proof-code").value="";
  get("mfa-modal-proof-submit").disabled=true;
  get("mfa-modal-proof-description").textContent=operation.kind==="disable_app"
    ?"To permanently remove every authenticator, verify with an existing device. You will then be signed out."
    :operation.kind==="remove"
      ?"To remove the selected authenticator, approve the change using a current six-digit code."
      :operation.kind==="rename"
        ?"Verify this display-name change with your current authenticator code."
        :operation.kind==="sign_in"
          ?"Verify this account sign-in policy change with an enrolled authenticator code."
          :"Verify an existing authenticator before adding another one.";
  metaStageSet("proof");
}
async function metaEnroll(){
  if(metaBusy || !metaValidName(metaDeviceName) || !csrfToken)return;
  metaBusy=true;
  try{
    const response=await request("/app/auth/mfa/totp/enroll",{name:metaDeviceName},csrfToken);
    if(response.status===409)throw Error("An unfinished setup exists. Cancel the previous setup before trying again.");
    if(response.status===429)throw Error("Too many setup requests. Try again after the security cooldown.");
    if(!response.ok)throw Error("Unable to start authenticator setup.");
    const body=await response.json();
    if(typeof body.factorId!=="string" || typeof body.secret!=="string"
      || !/^[A-Z2-7]{16,128}$/u.test(body.secret))
      throw Error("The provider returned an incomplete setup.");
    metaEnrollmentId=body.factorId;metaEnrollmentKey=body.secret;
    get("mfa-modal-key").textContent=body.secret;
    const qr=typeof body.qrCodeDataUrl==="string" &&
      body.qrCodeDataUrl.startsWith("data:image/svg+xml;base64,") &&
      body.qrCodeDataUrl.length<1500000?body.qrCodeDataUrl:"";
    const image=get("mfa-modal-qr");
    if(qr){image.src=qr;image.hidden=false;get("mfa-modal-qr-note").hidden=true;}
    else{image.removeAttribute("src");image.hidden=true;get("mfa-modal-qr-note").hidden=false;}
    metaStageSet("instructions");
  }catch(error){metaStatus(error instanceof Error?error.message:"Cannot start setup.");}
  finally{metaBusy=false;}
}
