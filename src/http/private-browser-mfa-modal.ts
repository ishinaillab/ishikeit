const metaDialog=get("mfa-dialog");
const metaStages=["overview","manage","connect","instructions","verify",
  "success","edit","rename","remove-confirm","method-confirm","proof"];
let metaStage="overview";
let metaSelected=null;
let metaDeviceName="";
let metaEnrollmentId="";
let metaEnrollmentKey="";
let metaOperation=null;
let metaProofReturn="manage";
let metaBusy=false;
function metaStatus(value){
  const output=get("mfa-modal-status");
  output.textContent=value||"";
  output.hidden=!value;
}
function metaValidName(value){
  const name=value.trim();
  return name.length>=1 && name.length<=64 && !/[\u0000-\u001f\u007f]/u.test(name);
}
function metaCodeInput(element,button){
  element.value=element.value.replace(/[^0-9]/gu,"").slice(0,6);
  button.disabled=!/^[0-9]{6}$/u.test(element.value) || metaBusy;
}
function metaStageSet(next){
  metaStage=next;
  for(const name of metaStages)get("mfa-modal-"+name).hidden=name!==next;
  get("mfa-modal-back").hidden=next==="overview" || next==="instructions";
  get("mfa-modal-title").textContent=next==="overview"
    ?"Two-factor authentication"
    : next==="manage"?"Authentication app"
    : next==="connect"?"Connect device"
    : next==="success"?"Setup complete"
    : "Account security";
  metaStatus("");
  if(next==="connect")get("mfa-modal-name").focus();
  if(next==="verify")get("mfa-modal-verify-code").focus();
  if(next==="proof")get("mfa-modal-proof-code").focus();
}
function metaItem(title,detail,handler,tail){
  const button=document.createElement("button");button.type="button";
  button.className="mfa-menu-item";
  const text=document.createElement("span");
  const name=document.createElement("strong");name.textContent=title;
  text.append(name);
  if(detail){const subtitle=document.createElement("small");
    subtitle.textContent=detail;text.append(subtitle);}
  const arrow=document.createElement("span");
  arrow.textContent=tail||"›";
  arrow.setAttribute("aria-hidden","true");
  button.append(text,arrow);
  button.addEventListener("click",handler);
  return button;
}
function metaRender(){
  if(!mfaState)return;
  const devices=mfaState.devices.filter(x=>x.enabled);
  const ready=devices.length>0;
  get("mfa-overview-heading").textContent=ready
    ?"Two-factor authentication is on":"Set up two-factor authentication";
  get("mfa-overview-description").textContent=ready
    ?(mfaState.signIn2faEnabled
      ?"Your connected authenticator apps help secure your Ishikeit sign-in."
      :"An authenticator is connected. The separate sign-in 2FA preference is off.")
    :"No authenticator app is currently configured. Add one to require codes from an authentication app.";
  const configured=get("mfa-configured-methods");
  const available=get("mfa-available-methods");
  configured.replaceChildren();available.replaceChildren();
  get("mfa-methods-heading").hidden=!ready;
  get("mfa-add-methods-heading").hidden=ready;
  if(ready)configured.append(metaItem("Authentication app",
    devices.length===1?"1 connected authenticator":String(devices.length)+" connected authenticators",
    ()=>metaStageSet("manage")));
  else available.append(metaItem("Authentication app",
    "Set up a new authenticator and verify its code",
    ()=>metaConnect()));
  const signInToggle=get("mfa-signin-toggle");
  signInToggle.disabled=!ready;
  signInToggle.setAttribute("aria-checked",mfaState.signIn2faEnabled?"true":"false");
  get("mfa-signin-status").textContent=mfaState.signIn2faEnabled?"On":"Off";
  const toggle=get("mfa-method-toggle");
  toggle.disabled=false;
  toggle.setAttribute("aria-checked",ready?"true":"false");
  get("mfa-method-onoff").textContent=ready?"On":"Off";
  const list=get("mfa-modal-devices");list.replaceChildren();
  if(!devices.length)list.append(metaItem("No connected devices","Add an authenticator to begin",()=>metaConnect(),"+"));
  for(const device of devices){
    list.append(metaItem(device.label,"Verified authenticator",
      ()=>{metaSelected=device;metaEdit();},"⋮"));
  }
}
async function metaRead(){
  const response=await fetch("/app/auth/mfa/factors",{
    credentials:"same-origin",cache:"no-store",redirect:"error"
  });
  if(!response.ok)throw Error("Authenticator state unavailable");
  const data=await response.json();
  if(!Array.isArray(data.devices))throw Error("Invalid authenticator state");
  renderMfaDeviceList(data);
  metaRender();
}
function metaClearKey(){
  metaEnrollmentId="";metaEnrollmentKey="";
  get("mfa-modal-key").textContent="";
  get("mfa-modal-qr").removeAttribute("src");
  get("mfa-modal-qr").hidden=true;
  get("mfa-modal-verify-code").value="";
  get("mfa-modal-verify-next").disabled=true;
}
async function metaCancelPending(){
  if(!metaEnrollmentId)return true;
  if(!csrfToken)throw Error("Sign-in expired");
  const response=await request("/app/auth/mfa/totp/reset",{},csrfToken);
  if(!response.ok)throw Error("Unable to cancel pending setup");
  metaClearKey();
  return true;
}
async function metaClose(){
  if(metaBusy)return;
  metaBusy=true;
  try{await metaCancelPending();}
  catch{metaStatus("Setup could not be canceled. Try again before closing.");metaBusy=false;return;}
  metaBusy=false;metaOperation=null;metaSelected=null;metaDeviceName="";
  if(typeof metaDialog.close==="function" && metaDialog.open)metaDialog.close();
  metaDialog.hidden=true;
}
