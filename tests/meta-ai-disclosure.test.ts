import { describe, expect, it, vi } from "vitest";
import type { BrainClient } from "../src/brain/types.js";
import type { StoredInboundEvent } from "../src/persistence/inbound.js";
import { MessageReceivedHandler } from "../src/processing/message-handler.js";
import { PostgresMetaDisclosureReader } from "../src/persistence/meta-disclosure.js";

const now = new Date().toISOString();
const makeEvent = (channel: "instagram" | "messenger" | "whatsapp" | "bot"): StoredInboundEvent => ({
  id: "11111111-1111-4111-8111-111111111111",
  partitionKey: "studio-account-1:customer-1",
  status: "persisted",
  event: {
    schemaVersion: 2, specversion: "1.0", id: "incoming-customer-1",
    source: "urn:ishikeit:source:meta:messenger:studio-account-1",
    type: "com.ishikeit.messaging.message.received",
    provider: channel === "bot" ? "telegram" : "meta", channel,
    capability: "messaging", accountId: "studio-account-1",
    eventType: "message.received", identityId: "customer-1",
    providerMessageId: "customer-message-1", receivedAt: now, occurredAt: now,
    content: [{ kind: "text", text: "Hello!" }], data: {}
  }
});

describe("Meta first-contact and re-entry bot disclosure", () => {
  it.each(["messenger", "instagram"] as const)(
    "adds a single explicit AI disclosure for first or long-gap %s customer contact",
    async channel => {
      const respond = vi.fn<BrainClient["respond"]>().mockResolvedValue({
        handoff: false, parts: [{ kind: "text", text: "8 AM is currently available." }]
      });
      const hasRecentAutomatedReply = vi.fn().mockResolvedValue(false);
      const stored = makeEvent(channel);
      const r = await new MessageReceivedHandler(
        {respond}, undefined, undefined, {hasRecentAutomatedReply}
      ).handle(stored);
      expect(r.actions).toHaveLength(1);
      expect(r.actions[0]?.body).toMatchObject({
        part: { kind: "text", text: "I'm Ishi Nail Lab's AI assistant.\n\n8 AM is currently available." }
      });
      expect(hasRecentAutomatedReply).toHaveBeenCalledWith(
        stored.partitionKey, new Date(now), stored.id
      );
    }
  );

  it("does not repeat a disclosure in a recent ongoing conversation", async () => {
    const respond = vi.fn<BrainClient["respond"]>().mockResolvedValue({
      handoff: false, parts: [{ kind: "text", text: "Yes, the appointment is available." }]
    });
    const r = await new MessageReceivedHandler(
      {respond}, undefined, undefined, {hasRecentAutomatedReply: ()=>Promise.resolve(true)}
    ).handle(makeEvent("instagram"));
    expect(r.actions[0]?.body).toMatchObject({
      part: { kind: "text", text: "Yes, the appointment is available." }
    });
  });

  it("does not duplicate a valid AI introduction already generated by the brain", async () => {
    const respond = vi.fn<BrainClient["respond"]>().mockResolvedValue({
      handoff: false, parts: [{kind:"text", text:"I'm Ishi Nail Lab's AI assistant. How can I help?"}]
    });
    const r = await new MessageReceivedHandler(
      {respond}, undefined, undefined, {hasRecentAutomatedReply: ()=>Promise.resolve(false)}
    ).handle(makeEvent("messenger"));
    expect(r.actions[0]?.body).toMatchObject({
      part: {kind:"text", text:"I'm Ishi Nail Lab's AI assistant. How can I help?"}
    });
  });

  it.each(["whatsapp", "bot"] as const)("does not apply Meta policy to %s", async channel => {
    const respond = vi.fn<BrainClient["respond"]>().mockResolvedValue({
      handoff: false, parts: [{kind:"text",text:"Welcome!"}]
    });
    const hasRecentAutomatedReply = vi.fn().mockResolvedValue(false);
    const r = await new MessageReceivedHandler(
      {respond}, undefined, undefined, {hasRecentAutomatedReply}
    ).handle(makeEvent(channel));
    expect(r.actions[0]?.body).toMatchObject({part:{kind:"text",text:"Welcome!"}});
    expect(hasRecentAutomatedReply).not.toHaveBeenCalled();
  });

  it("fails closed instead of sending unlabeled AI text when disclosure state is unreadable", async () => {
    const respond = vi.fn<BrainClient["respond"]>().mockResolvedValue({
      handoff: false, parts: [{kind:"text",text:"Hi"}]
    });
    await expect(new MessageReceivedHandler(
      {respond},undefined,undefined,{hasRecentAutomatedReply:()=>Promise.reject(new Error("DB unavailable"))}
    ).handle(makeEvent("messenger"))).rejects.toThrow("DB unavailable");
  });

  it("suppresses another disclosure only after a prior AI reply actually published", async () => {
    const earlier = "22222222-2222-4222-8222-222222222222";
    const query = vi.fn<(sql: string, args: readonly unknown[]) => Promise<{ rows: ({id?: string; delivered?: boolean})[]; rowCount: number }>>()
      .mockResolvedValueOnce({ rows: [{ id: earlier }], rowCount: 1 })
      .mockResolvedValueOnce({ rows: [{ delivered: true }], rowCount: 1 });
    const reader = new PostgresMetaDisclosureReader({ query } as never);
    expect(await reader.hasRecentAutomatedReply("partition-1", new Date(now),
      "11111111-1111-4111-8111-111111111111")).toBe(true);
    const [historySql, historyArgs] = query.mock.calls[0]!;
    expect(historySql).toContain("partition_key = $1");
    expect(historySql).toContain("processed_at IS NOT NULL");
    expect(historySql).toContain("ORDER BY received_at DESC LIMIT 256");
    expect(historyArgs).toEqual(["partition-1", new Date(now),
      "11111111-1111-4111-8111-111111111111"]);
    const [deliverySql, deliveryArgs] = query.mock.calls[1]!;
    expect(deliverySql).toContain("id = ANY($1::uuid[])");
    expect(deliverySql).toContain("published_at IS NOT NULL");
    expect(deliverySql).toContain("partition_key = $2");
    expect(deliveryArgs[0]).toHaveLength(1);
    expect(deliveryArgs[1]).toBe("partition-1");
  });

  it("rediscloses if earlier processing was handled but delivery is queued, unknown or dead-lettered", async () => {
    const query = vi.fn<(sql: string, args: readonly unknown[]) => Promise<{ rows: ({id?: string; delivered?: boolean})[]; rowCount: number }>>()
      .mockResolvedValueOnce({ rows: [{ id: "22222222-2222-4222-8222-222222222222" }], rowCount: 1 })
      .mockResolvedValueOnce({ rows: [{ delivered: false }], rowCount: 1 });
    const reader = new PostgresMetaDisclosureReader({ query } as never);
    expect(await reader.hasRecentAutomatedReply("partition-1", new Date(now),
      "11111111-1111-4111-8111-111111111111")).toBe(false);
  });

  it("does not query outbox when no earlier handled inbound exists", async () => {
    const query = vi.fn<(sql: string, args: readonly unknown[]) => Promise<{ rows: ({id?: string; delivered?: boolean})[]; rowCount: number }>>().mockResolvedValue({ rows: [], rowCount: 0 });
    const reader = new PostgresMetaDisclosureReader({ query } as never);
    expect(await reader.hasRecentAutomatedReply("partition-1", new Date(now),
      "11111111-1111-4111-8111-111111111111")).toBe(false);
    expect(query).toHaveBeenCalledOnce();
  });

  it("fails closed on missing durable delivery evidence", async () => {
    const query = vi.fn<(sql: string, args: readonly unknown[]) => Promise<{ rows: ({id?: string; delivered?: boolean})[]; rowCount: number }>>()
      .mockResolvedValueOnce({ rows: [{ id: "22222222-2222-4222-8222-222222222222" }], rowCount: 1 })
      .mockRejectedValueOnce(new Error("outbox unavailable"));
    const reader = new PostgresMetaDisclosureReader({ query } as never);
    await expect(reader.hasRecentAutomatedReply("partition-1", new Date(now),
      "11111111-1111-4111-8111-111111111111")).rejects.toThrow("outbox unavailable");
  });
});
